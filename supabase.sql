create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  avatar_url text,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists display_name text;
update public.profiles set display_name=coalesce(display_name, username) where display_name is null;
create unique index if not exists profiles_username_lower_unique on public.profiles (lower(username));

-- username is the login name; display_name is the visible name.
create or replace function public.get_email_by_username(login_username text)
returns text
language sql
security definer
set search_path = public
as $$
  select u.email
  from public.profiles p
  join auth.users u on u.id=p.id
  where lower(p.username)=lower(trim(login_username))
  limit 1;
$$;
revoke all on function public.get_email_by_username(text) from public;
grant execute on function public.get_email_by_username(text) to anon, authenticated;

