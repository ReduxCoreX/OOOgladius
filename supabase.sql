-- Automatically create an empty profile whenever a new auth user is created.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username, display_name) values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)), coalesce(new.raw_user_meta_data->>'display_name', new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();


-- Public participant profiles and administrator-controlled support reports.
-- Profiles contain no email column, so exposing these fields does not expose account email.
drop policy if exists "profiles_public_select" on public.profiles;
create policy "profiles_public_select" on public.profiles for select using (true);

create or replace function public.is_current_user_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid()
      and lower(trim(username)) = 'administrator'
  );
$$;
revoke all on function public.is_current_user_admin() from public;
grant execute on function public.is_current_user_admin() to authenticated;

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  reporter_username text not null,
  message text not null check (char_length(message) between 5 and 2000),
  status text not null default 'open' check (status in ('open','in_progress','closed')),
  admin_id uuid references auth.users(id) on delete set null,
  admin_username text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.reports enable row level security;

drop policy if exists "reports_select_own_or_admin" on public.reports;
create policy "reports_select_own_or_admin" on public.reports
for select using (auth.uid() = user_id or public.is_current_user_admin());

drop policy if exists "reports_insert_own" on public.reports;
create policy "reports_insert_own" on public.reports
for insert with check (auth.uid() = user_id);

drop policy if exists "reports_update_admin" on public.reports;
create policy "reports_update_admin" on public.reports
for update using (public.is_current_user_admin()) with check (public.is_current_user_admin());

create or replace function public.set_reports_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists reports_updated_at on public.reports;
create trigger reports_updated_at
before update on public.reports
for each row execute procedure public.set_reports_updated_at();


create or replace function public.set_reporter_username()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select p.username into new.reporter_username
  from public.profiles p
  where p.id = new.user_id;
  return new;
end;
$$;

drop trigger if exists reports_set_reporter_username on public.reports;
create trigger reports_set_reporter_username
before insert on public.reports
for each row execute procedure public.set_reporter_username();

-- API permissions required for the website.
grant select on public.profiles to anon, authenticated;
grant select, insert, update on public.reports to authenticated;
grant usage, select on sequence public.reports_id_seq to authenticated;
grant execute on function public.is_current_user_admin() to authenticated;


