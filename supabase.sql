create table if not exists public.report_chat_messages (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender_username text,
  message text not null check (char_length(message) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.report_chat_messages enable row level security;

create or replace function public.set_chat_sender_username()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select p.username
  into new.sender_username
  from public.profiles p
  where p.id = new.sender_id;
  return new;
end;
$$;

drop trigger if exists report_chat_set_sender_username
on public.report_chat_messages;

create trigger report_chat_set_sender_username
before insert on public.report_chat_messages
for each row
execute procedure public.set_chat_sender_username();

drop policy if exists "chat_select_participants"
on public.report_chat_messages;

create policy "chat_select_participants"
on public.report_chat_messages
for select
using (
  exists (
    select 1
    from public.reports r
    where r.id = report_chat_messages.report_id
      and r.status = 'in_progress'
      and (r.user_id = auth.uid() or r.admin_id = auth.uid())
  )
);

drop policy if exists "chat_insert_participants"
on public.report_chat_messages;

create policy "chat_insert_participants"
on public.report_chat_messages
for insert
with check (
  sender_id = auth.uid()
  and exists (
    select 1
    from public.reports r
    where r.id = report_chat_messages.report_id
      and r.status = 'in_progress'
      and (r.user_id = auth.uid() or r.admin_id = auth.uid())
  )
);

grant select, insert
on public.report_chat_messages
to authenticated;

grant usage, select
on sequence public.report_chat_messages_id_seq
to authenticated;

grant execute
on function public.set_chat_sender_username()
to authenticated;

